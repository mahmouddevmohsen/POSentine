-- ── 1) العمود — JSONB، اختياري، بدون قيمة افتراضية غير NULL ──────
alter table public.shift_reports
  add column if not exists top_items jsonb;

comment on column public.shift_reports.top_items is
  'ناتج metrics.top_items() زي ما هو — مصفوفة [ [name, qty], ... ] بترتيب '
  'الكمية تنازلي، أقصى top_n بند (افتراضي 5). NULL لأي وردية اتسجلت قبل '
  'هذا العمود، أو لو مفيش سطور فواتير للوردية دي. مفيش حساب تاني بيحصل '
  'هنا — القيمة منسوخة زي ما orchestrator.py بيحسبها بالظبط.';

-- ── 2) الصلاحية — مضمونة أصلاً بالـGRANT الحالي (schema_v8)، بس ──
--     بنعيدها هنا صراحة عشان الملف يبقى مستقل وقابل للتشغيل لوحده
--     من غير الاعتماد على ترتيب تشغيل الملفات القديمة.
grant select on public.shift_reports to dashboard_ro;

