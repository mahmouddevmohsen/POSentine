-- ── 1) العمود — JSONB، اختياري، بدون قيمة افتراضية غير NULL ──────
alter table public.shift_reports
  add column if not exists other_users jsonb;

comment on column public.shift_reports.other_users is
  'ناتج metrics.compute_shift() م.other_users زي ما هو — مصفوفة كائنات '
  '[ {"uid":.., "name":.., "invoices":.., "amount":..}, ... ]، مرتبة زي '
  'ما orchestrator.py بيبنيها (ranked[1:] بعد المستخدم الأساسي). قيمة '
  'كل مستخدم هنا محسوبة أصلاً ضمن إجمالي الوردية — ماتتضافش تاني على '
  'grand_total. مصفوفة فاضية [] لو مفيش مستخدمين تانيين ساهموا في '
  'الوردية دي؛ NULL بس للورديات القديمة اللي اتسجلت قبل هذا العمود. '
  'مفيش حساب تاني بيحصل هنا.';

